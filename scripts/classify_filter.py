# 判定保守：要求 PE 词与主体代词（你公司/你企业/你方/该公司/当事人）在合理窗口内由谓词（作为/系/从事/开展…）连系。
SUBJECT_PE = re.compile(
    r"(你公司|你企业|你方|该公司|当事人|贵公司)"            # 被处罚主体代词
    r".{0,14}"                                            # 间隔（容错 OCR/套话）
    r"(作为|系|为|是|属于|从事|开展|设立|管理|存在|在)"       # 主体与私募的谓词
    r".{0,12}"                                            # 间隔
    r"(私募基金管理人|私募投资基金管理业务|私募投资基金管理|私募基金业务|私募证券投资|私募资产管理)"
    r"|(私募基金管理人|私募投资基金管理业务|私募基金业务)"     # 也可 PE 词在前、主体代词在后
    r".{0,18}(你公司|你企业|你方|该公司|当事人)"
    r"|(你(同志|：)?|该人|当事人).{0,10}(作为|系|为|是).{0,6}私募基金从业人员"  # 从业人员（自然人）
)
# 【注销/撤销私募基金管理人登记】决定性阳性（用户 2026-10-29 补裁定，P2 路径）：
# 若决定书【名称或正文】表明该处罚即「注销/撤销（私募基金管理人）登记」，
# 则无需查 AMAC —— 能被注销/撤销私募基金管理人登记的，必然曾是已登记私募管理人，
# 直接认定私募机构、必须收录。这恰好覆盖「被处罚私募被注销」的边缘情况
# （文书本身就是注销动作的证明；AMAC 在册名册查不到此主体时，此路仍成立）。
# 用词保守（严谨完备）：必须锚定「私募基金管理人/基金管理人登记」，避免
# 「工商注销登记」「撤销证券业务许可」等非私募语境误触发——
# 且金融持牌机构已在下方步骤1被硬剔除，双重保险。
CANCEL_REG = re.compile(
    r"(注销|撤销|取消).{0,10}(私募基金管理人登记|私募投资基金管理人登记|"
    r"基金管理人登记|私募基金管理人.{0,4}(登记|资格))"
    r"|私募基金管理人.{0,18}(被注销|被撤销|予以注销|予以撤销|注销登记|撤销登记|"
    r"登记被注销|登记被撤销)"
    r"|关于(注销|撤销|取消).{0,25}私募基金管理人登记")


def classify_pf(text, subject="", title=""):
    """判定文书是否属于【私募基金监管】范畴，返回 (是否收录, 判定依据, 证据强度)。

    唯一决定性阳性标准（用户 2026-10-29 最终裁定，优先于名称判断）：
    被处罚主体在中国证券投资基金业协会完成【私募基金管理人登记】（含被注销/撤销登记），
    即认定为私募机构、必须收录；名称像不像私募、引用了什么法都不应误杀
    （存在「企业管理咨询/网络科技/投资管理」命名的真实私募管理人特例）。
    用户补充（2026-10-29）：有登记产品但从未登记为管理人的，不是本库要的案例——
    故名册倒查只查【管理人】名册（在册+已注销），不查产品名册，天然排除产品-only 实体。

    三条【互相独立、任一即可定案】的确证路径（P1/P2/P3），全部压倒名称/法规噪声：
      P1 文书倒查（AMAC_REG）：正文出现登记编号(P/S)、「完成私募基金管理人登记」、
          「私募基金产品备案」「合伙型私募基金」等 → 收；
      P2 注销登记处罚（CANCEL_REG，用户 2026-10-29 补裁定）：决定书【名称或正文】表明
          处罚即「注销/撤销私募基金管理人登记」→ 收（无需查 AMAC，能被注销登记的必然曾是
          已登记私募管理人；正好覆盖「被处罚私募被注销」情形）；
      P3 AMAC 管理人名册倒查（amac_lookup.is_registered_manager，管道第二遍复核）：
          被处罚主体名命中 AMAC【在册 + 已注销】管理人名册 → 收（兜底查不到 P1/P2 证据的
          主体、以及「先被处罚、后被注销」的真实私募管理人）。该名册须随库更新重下。

    证据强度 strength（供 P3 名册闸门区分「压倒性文本证据」与「可能第三方提及的软证据」）：
      'hard'    —— 决定性文本证据：AMAC_REG（登记编号/备案）、CANCEL_REG（注销登记）、
                  SUBJECT_PE（文书直接指认『你公司/你企业』为私募基金管理人/从业人员）、
                  或【正文点名主体为私募基金管理人/业务】（高管/从业人员同案，机构以全称出现）。
                  即便名册未命中（名称变异）也应收录，不被 P3 闸门推翻。
      'soft'    —— 软证据：_PF_NAME+PF_LAWS / PF_WEAK+_PF_NAME。
                  可能是主体本身，也可能是「第三方私募」被顺带提及 → 必须由 P3 名册复核：
                  名册未命中则推翻为剔除（排除上市公司等顺带引用私募法的假阳性）。
      'exclude' —— 不收（金融持牌机构硬阴性、或任何私募线索均无）。

    text 与 title 共同构成「名称或内容」正文字面（P1/P2 在其中检索）；
    subject 用于【主体名】层面的硬阴性/软阳性判定，并在步骤 5.5 参与「正文点名主体为私募」
    的文本匹配（主体全称指代，覆盖高管/从业人员同案）；subject 不参与 P1/P2 检索，
    以免「标题含私募」误伤主体本身为非私募金融机构的文书。

    判定顺序（关键：金融持牌机构硬阴性必须先于一切私募软阳性，否则券商/期货/银行/信托/
    保险/公募/基金销售 的私募资管类处罚会被误收）：
      1) 主体名明确为「绝不会是中基协私募管理人」的持牌金融机构（_NOT_PF_NAME）→ 剔；
      2) 明确非私募特定主体（KNOWN_NON_PF，SKILL.md §0.3 裁定）→ 剔；
      3) P2 注销/撤销私募基金管理人登记处罚（CANCEL_REG，查 text+title）→ 收（hard）；
      4) P1 中基协登记/备案决定性证据（AMAC_REG，查 text+title）→ 收（hard）；
      5) 文书直接载明被处罚主体（你公司/你企业）为私募基金管理人/从业人员（SUBJECT_PE）→ 收（hard）；
      5.5) 正文点名主体（管理人全称）为私募基金管理人/从事私募业务，或其从业人员同案（高管并罚）
           → 收（hard，覆盖机构以全称出现、无『你公司』指代的高管/从业人员同案情形）；
      6) 软阳性：引用私募专属法规/私募专指词 且 主体名像私募机构（_PF_NAME）→ 收（soft）；
      7) 弱阳性：协会名 + 主体名像私募 → 收（soft）；
      8) 否则剔除（名称像私募但无任何登记/协会/私募法线索 → 保守不收；P3 可能后续覆盖）。
    """
    f = re.sub(r"\s+", "", (text or "") + "\n" + (title or ""))
    subj = subject or ""
    if subj and _NOT_PF_NAME.search(subj):
        return False, "主体名为非私募金融机构", "exclude"
    if subj and KNOWN_NON_PF.search(subj):
        return False, "明确非私募主体（SKILL.md §0.3）", "exclude"
    # P2：注销/撤销私募基金管理人登记处罚 —— 直接认定私募机构，无需 AMAC 查询（hard）
    if CANCEL_REG.search(f):
        return True, "注销/撤销私募基金管理人登记处罚（主体曾为已登记私募管理人，决定性证据）", "hard"
    # P1：中基协登记/备案决定性证据（压倒一切名称/法规噪声）（hard）
    if AMAC_REG.search(f):
        return True, "中基协登记/备案（私募机构决定性证据）", "hard"
    # 文书直接载明被处罚主体（你公司/你企业）为私募基金管理人/从业人员/从事私募基金管理业务
    # → 收（hard，决定性文本证据）。必须「主体绑定」（SUBJECT_PE），避免正文提及【第三方】私募被误收
    # （浙江泰坦/贝斯美/常州国润九号 曾因第三方提及被误救）。金融持牌机构已在步骤1被硬剔除。
    # 这是「下载文书倒查」的核心：监管直接指认该主体为私募基金管理人/业务，压倒名称/名册噪声。
    if SUBJECT_PE.search(f):
        return True, "文书载明被处罚主体（你公司/你企业）为私募基金管理人/从业人员", "hard"
    # 主体名（管理人）在正文被【点名】且语境为私募基金管理/业务（含「你作为X从业人员」式
    # 高管/从业人员同案）——覆盖「被处罚主体是某私募管理人的高管/从业人员、但文书用机构全称
    # 而非『你公司』指代」的情形（程鹏-天津暖流：正文『天津暖流…在从事私募基金业务活动…
    # 你作为天津暖流…从业人员』，主体以全称出现、无『你公司』，SUBJECT_PE 不命中）。
    # 此为决定性文本证据（hard）：监管点名该机构为私募基金管理人/业务或其从业人员。
    # 与 SUBJECT_PE 同理要求「主体绑定」，绝不因正文出现任何『私募』二字就收——必须点名主体
    # 自身或其从业人员语境。金融持牌机构已在步骤1被硬剔除。
    if subj:
        _core = _strip_suffix(subj)
        if _core and len(_core) >= 3:
            _named_mgr = re.escape(_core) + r".{0,30}(在从事|从事|系|作为|为|是|管理)" \
                                          r".{0,12}(私募基金管理人|私募基金业务|私募投资基金管理|私募资产管理)"
            _named_emp = re.escape(_core) + r".{0,24}(私募基金管理人|私募投资基金管理业务)"
            if re.search(_named_mgr, f) or re.search(_named_emp, f):
                return True, "正文点名主体（%s）为私募基金管理人/从事私募业务" % subj, "hard"
    # 文书引用私募专属法规 或 含私募专指词，且主体名像私募机构 → 收（soft）
    # （要求主体名像私募机构，避免上市公司等顺带引用私募法被误收）
    if subj and _PF_NAME.search(subj) and (PF_LAWS.search(f) or any(k in f for k in PF_STRONG)):
        return True, "主体像私募机构且文书含私募证据", "soft"
    # 弱阳性：协会名 + 主体名像私募 → 收（soft）
    if subj and any(k in f for k in PF_WEAK) and _PF_NAME.search(subj):
        return True, "主体为私募机构（%s）" % subj, "soft"
    return False, "与私募基金监管无关", "exclude"


def is_private_fund(text, subject="", title=""):
    """向后兼容薄包装：返回 (是否收录, 判定依据)，丢弃证据强度。

    新代码请改用 classify_pf（可拿到 strength 以便 P3 名册闸门区分 hard/soft）。
    """
    inc, why, _ = classify_pf(text, subject, title)
    return inc, why


