def recat(cat, source):
    """把六分法通用名映射到对应来源的目录名。cat 为 None 时返回 None（规则无法判定）。"""
    if not cat:
        return None
    if cat.startswith('06_'):
        return '06_其他自律违规' if source == '中基协' else '06_其他行政违规'
    return cat


def rule_classify(txt, need_confident=False):
    """关键词加权分类（原始类目，未 recat）。

    need_confident=True 时要求「最高分 ≥4 且领先第二名 ≥50%」，否则返回 None
    （表示规则无法自信判定，不参与与台账的差异比对，避免噪声）。
    """
    text = txt or ""
    scores = sorted(((sum(text.count(k) * (3 if k in STRONG_KW else 1) for k in kws), cat)
                    for cat, kws in CATS), reverse=True)
    if not scores or scores[0][0] == 0:
        return None
    if need_confident:
        if scores[0][0] < 4:
            return None
        second = scores[1][0] if len(scores) > 1 else 0
        if second and scores[0][0] < second * 1.5:
            return None
    return scores[0][1]


