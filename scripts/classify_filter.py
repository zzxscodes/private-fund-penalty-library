def _strip_suffix(name):
    """剥掉主体名尾部的公司/合伙后缀，返回核心名（容差匹配用）。"""
    n = (name or "").strip()
    for suf in sorted(_SUFFIXES, key=len, reverse=True):
        if n.endswith(suf) and len(n) > len(suf):
            return n[: -len(suf)]
    return n


