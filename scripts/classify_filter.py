def classify_exch(text, need_confident=False):
    """交易所文书专用分类（四分法：01/02/03 + 04_其他自律监管）。

    兜底必须是 `04_其他自律监管`——**绝不能**返回「06_其他行政违规」（那是证监局六分法的
    序号与「行政」口径，落在自律监管目录下既不合法也难检索）。
    实测事故：北交所「拉抬股价、异常交易」决定书被写成 06_其他行政违规 并落在 03/06 目录。
    """
    t = re.sub(r"\s+", "", text or "")
    scores = sorted(((sum(t.count(k) * (3 if k in EXCH_STRONG else 1) for k in kws), cat)
                     for cat, kws in EXCH_RULES), reverse=True)
    if not scores or scores[0][0] == 0:
        return EXCH_FALLBACK
    if need_confident and scores[0][0] < 4:
        return EXCH_FALLBACK
    return scores[0][1]


# 证券投资顾问/咨询业务违规：不属六分法任何一类，统一归「其他」。
# 2026-10-30 用户裁定：「属于注册或注销名册的就保留，但这种不是明显分类的放到每一个信源的
#   其他子分类去」。实践场景：曾在协会登记过私募管理人、现已注销（或仍存续）的机构，
#   被罚的却是**证券投资顾问业务**（误导性宣传、投资建议无合理依据、直播展业不规范、
#   未取得投顾资格人员展业等，引《证券投资顾问业务暂行规定》）。这类既不是募集/适当性，
#   也不是登记备案/投资运作/内控——强行塞进六分法会误导演示与培训取用，必须落 06_其他。
_ADVISORY_PAT = re.compile(r"(证券投资顾问业务|证券投资咨询业务|证券投资顾问|投资顾问服务|荐股软件)")
# 出现下列表述说明案件本身涉及私募基金业务实质 → 不能判为「纯投顾案」
_PF_BIZ_PAT = re.compile(r"(私募基金|私募投资|基金管理人|基金财产|基金份额|基金合同|备案的基金|私募证券投资基金)")


def is_advisory_only(text):
    """纯证券投顾/咨询业务违规（不含私募基金业务实质）→ True。"""
    t = text or ""
    if not _ADVISORY_PAT.search(t):
        return False
    return not _PF_BIZ_PAT.search(t)


def classify(text, source=None, need_confident=False):
    """供 build 使用的分类入口：返回已按来源 recat 的目录名。

    - source=='交易所' → 走 EXCH_RULES 四分法（**绝不能**返回通用六分法目录名，
      否则会在 03 顶层建出不存在的子目录，见上方 2026-10-29 教训）。
    - 其余 source 走六分法；source 为 None 时返回六分法通用名（不带 06_来源后缀）。
    - 纯证券投顾业务案（见 is_advisory_only）优先落 06_其他，不进六分法。
    - need_confident=False：始终返回最佳猜测（无关键词时回退 06_其他）。
    """
    if source == "交易所":
        return classify_exch(text or "", need_confident=need_confident)
    if is_advisory_only(text):
        return recat("06_其他行政违规", source) if source else "06_其他"
    raw = rule_classify(text or "", need_confident=need_confident)
    if raw is None:
        return recat(CAT_DEFAULT, source) if source else CAT_DEFAULT
    return recat(raw, source) if source else raw


