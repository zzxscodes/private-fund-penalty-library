def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    root = os.path.abspath(a.root)
    ledger = next(os.path.join(root, f) for f in os.listdir(root)
                  if f.startswith("04_") and f.endswith(".xlsx") and not f.startswith("~$"))
    wb = openpyxl.load_workbook(ledger)
    ws = wb.active
    for row, kv in SET.items():
        print("== 行%d %s" % (row, str(ws.cell(row, 4).value)[:36]))
        for col, v in sorted(kv.items()):
            print("   列%s 旧：%s" % ("ABCDEFGHIJKLMNO"[col], str(ws.cell(row, col + 1).value)[:60].replace("\n", " ⏎ ")))
            print("   列%s 新：%s" % ("ABCDEFGHIJKLMNO"[col], v[:60].replace("\n", " ⏎ ")))
    if not a.apply:
        print("\n[干跑] 未改动；确认后加 --apply")
        return
    backup_ledger(root, ledger, "revcontent")
    for row, kv in SET.items():
        for col, v in kv.items():
            ws.cell(row, col + 1).value = v
    wb.save(ledger)
    print("已保存 %d 行 / %d 个单元格" % (len(SET), sum(len(v) for v in SET.values())))


if __name__ == "__main__":
    main()
