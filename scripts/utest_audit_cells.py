def main():
    fails = 0
    for col, s, code, desc in CASES:
        hits = check_cell(col, s, 2)
        if code not in hits:
            print("FAIL 正例未命中：%s（期望 %s，实际 %s）" % (desc, code, hits))
            fails += 1
    for col, s, code, desc in NEG:
        hits = check_cell(col, s, 2)
        if code in hits:
            print("FAIL 反例误报：%s（不该命中 %s）" % (desc, code))
            fails += 1
    if fails:
        print("\nFAIL %d 项" % fails)
        return 1
    print("PASS 逐格体检器反向断言通过：正例 %d / 反例 %d" % (len(CASES), len(NEG)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
