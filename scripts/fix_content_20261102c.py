def find_row(ws, match):
    """按「主体 + 落款日（+ 可选来源）」三元组定位，避免同机构多案时命中错行。

    2026-11-02 血泪：中核华瑞有 2 行（中基协 2026-02-11 / 证监局 2026-03-16），
    只按主体匹配会命中第一行，把证监局的事由写进中基协那行（实测已拦下）。
    """
    key, val = match[0], match[1]
    want_date = match[2] if len(match) > 2 else ""
    for r in range(2, ws.max_row + 1):
        got = str(ws.cell(r, C[key] + 1).value or "").strip()
        if val not in got:
            continue
        if want_date and str(ws.cell(r, C["decided"] + 1).value or "")[:10] != want_date:
            continue
        return r
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    root = os.path.abspath(a.root)
    ledger = next(os.path.join(root, f) for f in os.listdir(root)
                  if f.startswith("04_") and f.endswith(".xlsx") and not f.startswith("~$"))
    wb = openpyxl.load_workbook(ledger)
    ws = wb.active

    todo, skip = [], []
    for fx in FIXES:
        r = find_row(ws, fx["match"])
        if r is None:
            skip.append((fx["tag"], "找不到匹配合规行"))
            continue
        cur = str(ws.cell(r, C[fx["col"]] + 1).value or "").strip()
        if "old_eq" in fx:
            ok = cur == fx["old_eq"]
        else:
            ok = fx["old_has"] in cur
        if not ok:
            skip.append((fx["tag"], "旧值不匹配（现为 %r）" % cur[:28]))
            continue
        todo.append((r, fx))
        print("  ✓ %-34s 行%-4d 列=%s" % (fx["tag"], r, fx["col"]))
        print("      %s" % fx["new"][:64].replace("\n", " ⏎ "))

    if skip:
        print("\n【跳过 %d 条】" % len(skip))
        for t, why in skip:
            print("  · %s ｜%s" % (t, why))
    if not a.apply:
        print("\n（dry-run；--apply 落盘）")
        return
    if not todo:
        print("\n无改动。")
        return
    from ledger_bak import backup_ledger
    print("\n台账已备份：%s" % backup_ledger(root, ledger, "fix_content_c"))
    for r, fx in todo:
        ws.cell(r, C[fx["col"]] + 1).value = fx["new"]
    wb.save(ledger)
    print("\n已改 %d 处" % len(todo))


if __name__ == "__main__":
    main()
