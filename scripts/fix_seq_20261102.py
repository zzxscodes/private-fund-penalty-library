def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--ledger", default="")
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    ledger = args.ledger or os.path.join(root, "04_综合索引台账【总表】.xlsx")
    wb = openpyxl.load_workbook(ledger)
    ws = wb.worksheets[0]

    n_ok = 0
    bad = []
    for row, target, must, docno in FIXES:
        old = ws.cell(row, 6).value or ""
        subject = str(ws.cell(row, 4).value or "")
        missing = [k for k in must if k not in target]
        if missing:
            bad.append((row, "目标值缺关键句：%s" % ",".join(missing)))
            continue
        if old.strip() == target.strip():
            print("行%-4d 已是目标值，跳过" % row)
            n_ok += 1
            continue
        print("\n行%-4d %s（%s）" % (row, subject[:34], docno))
        print("  旧 %d 字 / %d 条 → 新 %d 字 / %d 条"
              % (len(old), old.count("\n") + 1, len(target), target.count("\n") + 1))
        print("  新 %s" % target[:110].replace("\n", " ⏎ "))
        if args.apply:
            ws.cell(row, 6).value = target
        n_ok += 1

    print("\n处理 %d 行｜异常 %d" % (n_ok, len(bad)))
    for row, why in bad:
        print("  行%-4d %s" % (row, why))

    if args.apply and n_ok:
        backup_ledger(root, ledger, "seq_20261102")
        wb.save(ledger)
        print("\n已保存（备份在 _案例库维护留痕/台账备份/）")
    elif not args.apply:
        print("\n[干跑] 未落盘；加 --apply 执行")
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main())
